import Foundation

/// Protocol constants shared by host and clients.
public enum Mirage {
    public static let protocolVersion = 3
    public static let alpn = "mirage/1"
    public static let defaultPort: UInt16 = 7799
    /// Domain-separation prefix for every hash/signature in the protocol.
    public static let dsi = "mirage-v1"
    /// QUIC idle timeout on both ends. A 30 s outage must not close the connection (§4a); dead peers are
    /// noticed sooner by the viewer's stall watchdog (no host packet for 12 s → redial and resume) and by
    /// ICMP unreachable when the host process is gone.
    public static let idleTimeoutMs: Int = 45_000
    /// Viewer keepalive: one small datagram ping this often.
    public static let keepaliveSeconds = 10
    /// A suspended session waits this long for its viewer to come back.
    public static let resumeWindowSeconds = 300
}

/// Length-prefixed JSON frames on a reliable QUIC stream.
/// [u32 big-endian payload length][JSON payload]
public enum Frame {
    public static let maxLength = 1 << 20

    public static func encode<T: Encodable>(_ value: T) throws -> Data {
        let body = try JSONEncoder().encode(value)
        precondition(body.count <= maxLength)
        var out = Data(capacity: 4 + body.count)
        var len = UInt32(body.count).bigEndian
        withUnsafeBytes(of: &len) { out.append(contentsOf: $0) }
        out.append(body)
        return out
    }

    public static func decode<T: Decodable>(_ type: T.Type, from body: Data) throws -> T {
        try JSONDecoder().decode(type, from: body)
    }

    public static func length(from header: Data) -> Int {
        precondition(header.count == 4)
        return Int(header.withUnsafeBytes { $0.loadUnaligned(as: UInt32.self) }.bigEndian)
    }
}

/// Every message on the control stream. JSON is fine for the control plane;
/// pixel data will get its own binary framing on other streams.
public enum ControlMessage: Codable, Equatable {
    /// Whether an input message was generated by a script rather than a person.
    public var isScripted: Bool {
        switch self {
        case .mouseMove(let m): return m.scripted ?? false
        case .mouseButton(let m): return m.scripted ?? false
        case .scroll(let s): return s.scripted ?? false
        case .key(let k): return k.scripted ?? false
        default: return false
        }
    }
    /// Normalized pointer position of an input message, if it has one.
    public var inputPoint: (x: Double, y: Double)? {
        switch self {
        case .mouseMove(let m): return (m.x, m.y)
        case .mouseButton(let m): return (m.x, m.y)
        case .scroll(let s): return (s.x, s.y)
        default: return nil
        }
    }
    /// Marks an input message as scripted.
    public func markedScripted() -> ControlMessage {
        switch self {
        case .mouseMove(var m): m.scripted = true; return .mouseMove(m)
        case .mouseButton(var m): m.scripted = true; return .mouseButton(m)
        case .scroll(var s): s.scripted = true; return .scroll(s)
        case .key(var k): k.scripted = true; return .key(k)
        default: return self
        }
    }
    /// The input sequence number carried by an input message, if any.
    public var inputSeq: UInt64? {
        switch self {
        case .mouseMove(let m): return m.seq
        case .mouseButton(let m): return m.seq
        case .scroll(let s): return s.seq
        case .key(let k): return k.seq
        case .modifiers(let m): return m.seq
        default: return nil
        }
    }
    /// A discrete input event (everything but pointer moves): sequenced, applied exactly once.
    public var isDiscreteInput: Bool {
        switch self {
        case .mouseButton, .scroll, .key, .modifiers: return true
        default: return false
        }
    }

    // Session authentication (paired devices).
    case hello(Hello)
    case challenge(Challenge)
    case authenticate(Authenticate)
    case welcome(Welcome)
    case reject(Reject)

    // Pairing (CPace over X25519, see Crypto/CPace.swift).
    case pairRequest(PairRequest)
    case pairChallenge(PairChallenge)
    case pairConfirm(PairConfirm)
    case pairAccept(PairAccept)
    case pairIdentity(PairIdentity)
    case pairComplete(PairComplete)

    // Liveness / latency.
    case ping(Ping)
    case pong(Ping)

    // Desktop streaming (M1).
    case streamRequest(StreamRequest)
    case streamInfo(StreamInfo)
    case streamStop
    case frameAck(FrameAck)
    case cursorShape(CursorShape)
    case cursorPosition(CursorPosition)

    // M2: tile-stream acks (feedback), host window list, rate-controller state for the overlay.
    case tileAck(TileAck)
    case windowList(WindowList)
    case rateState(RateState)
    /// What the host is looking at: console lock state, frontmost app and window (once a second).
    case hostStatus(HostStatus)
    /// Viewer → host: resend these fragments of a recent frame (fragment NACK; an empty list = the whole frame).
    case nack(Nack)
    /// Viewer → host (M3, layered desktop): a window-management result decided locally (a drag, a raise,
    /// a minimize) that the host applies through Accessibility.
    case windowCommand(WindowCommand)
    /// Viewer → host: these tiles of a layer have no clean pixels on the viewer (it dropped a write that might
    /// have held a window, or they predate the window becoming a layer); resend them once clear of windows.
    case refreshTiles(RefreshTiles)

    // Input, client → host. Coordinates are normalized to the streamed display: (0,0) top-left, (1,1) bottom-right.
    case mouseMove(MouseMove)
    case mouseButton(MouseButton)
    case scroll(Scroll)
    case key(Key)
    case modifiers(Modifiers)

